import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import * as mdiPaths from "@mdi/js";

const REPOSITORY_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_ROOT = join(REPOSITORY_ROOT, "src");
const OUTPUT_PATH = join(SOURCE_ROOT, "materialdesignicons-subset.css");
const SUPPORTED_EXTENSIONS = new Set([".css", ".html", ".ts", ".tsx"]);
const MODIFIER_CLASSES = new Set(["mdi-18px"]);
const ICON_CLASS_PATTERN = /\bmdi-[a-z0-9-]+\b/g;
const GENERATED_HEADER = "/* Generated by scripts/generate-mdi-subset.mjs. Do not edit. */";

const checkOnly = process.argv.includes("--check");

function exportNameForClass(className) {
  return `mdi${className
    .slice(4)
    .split("-")
    .map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join("")}`;
}

async function collectSourceFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolutePath = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...await collectSourceFiles(absolutePath));
      continue;
    }
    if (
      entry.isFile()
      && SUPPORTED_EXTENSIONS.has(extname(entry.name))
      && absolutePath !== OUTPUT_PATH
      && entry.name !== "materialdesignicons.min.css"
    ) {
      files.push(absolutePath);
    }
  }
  return files;
}

async function collectUsedIconClasses() {
  const classNames = new Set();
  for (const filePath of await collectSourceFiles(SOURCE_ROOT)) {
    const source = await readFile(filePath, "utf8");
    for (const match of source.matchAll(ICON_CLASS_PATTERN)) {
      classNames.add(match[0]);
    }
  }
  return [...classNames]
    .filter((className) => !MODIFIER_CLASSES.has(className))
    .sort();
}

function svgDataUrl(pathData) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${pathData}"/></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

function renderSubset(iconClasses) {
  const rules = iconClasses.map((className) => {
    const exportName = exportNameForClass(className);
    const pathData = mdiPaths[exportName];
    if (typeof pathData !== "string" || pathData.length === 0) {
      throw new Error(
        `No @mdi/js path exists for ${className} (${exportName}). `
        + "Declare a supported modifier or use a valid Material Design icon class.",
      );
    }
    return `.${className}::before { --uf-mdi-icon: url("${svgDataUrl(pathData)}"); }`;
  });

  return `${GENERATED_HEADER}
.mdi {
  display: inline-block;
  width: 1em;
  height: 1em;
  flex: 0 0 auto;
  vertical-align: -0.125em;
}

.mdi::before {
  content: "";
  display: block;
  width: 100%;
  height: 100%;
  background-color: currentColor;
  -webkit-mask-image: var(--uf-mdi-icon, linear-gradient(transparent, transparent));
  mask-image: var(--uf-mdi-icon, linear-gradient(transparent, transparent));
  -webkit-mask-position: center;
  mask-position: center;
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-size: contain;
  mask-size: contain;
}

.mdi-18px {
  width: 18px;
  height: 18px;
}

${rules.join("\n")}
`;
}

const iconClasses = await collectUsedIconClasses();
const generated = renderSubset(iconClasses);

if (checkOnly) {
  let current = "";
  try {
    current = await readFile(OUTPUT_PATH, "utf8");
  } catch {
    // Report the same actionable stale-output error for absent and changed files.
  }
  if (current !== generated) {
    throw new Error(
      `${relative(REPOSITORY_ROOT, OUTPUT_PATH)} is stale. Run pnpm icons:generate.`,
    );
  }
  console.log(`Verified ${iconClasses.length} generated Material Design icon masks.`);
} else {
  await writeFile(OUTPUT_PATH, generated, "utf8");
  console.log(`Generated ${iconClasses.length} Material Design icon masks.`);
}
